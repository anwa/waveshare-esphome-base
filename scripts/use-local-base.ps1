<#
.SYNOPSIS
Writes a local-development entry file that points a consuming project at this
working tree of waveshare-esphome-base.

.DESCRIPTION
A consuming project references the base through one committed package file,
for example packages/waveshare-base.yaml, that loads the base from GitHub at a
fixed tag. This script reads the file list of that package file and writes a
sibling file with the suffix .local.yaml that loads the same files from this
working tree instead, together with the local waveshare_ui component.

The generated file contains absolute local paths and must never be committed.
The consuming project ignores *.local.yaml; the script refuses to write the
file otherwise.

Validate or compile the project against the local base with:

    esphome -s waveshare_base_package <relative path of the .local.yaml> config <root yaml>

Without the -s option the project builds against the pinned tag again.

.PARAMETER ProjectRoot
Root directory of the consuming project. Defaults to the current directory.

.PARAMETER Package
Committed base package file, relative to ProjectRoot.
#>
[CmdletBinding()]
param(
    [string]$ProjectRoot = (Get-Location).Path,
    [string]$Package = "packages/waveshare-base.yaml"
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$BaseRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path -replace '\\', '/'
$ProjectRoot = (Resolve-Path $ProjectRoot).Path
$PackageFile = Join-Path $ProjectRoot $Package

if (-not (Test-Path -LiteralPath $PackageFile -PathType Leaf)) {
    throw "Base package file not found: $PackageFile"
}

# The committed package file lists the base files on one line, for example:
#   files: [base.yaml, optional/ha-motion.yaml]
$filesLine = Select-String -LiteralPath $PackageFile -Pattern '^\s*files:\s*\[(.+)\]\s*$' | Select-Object -First 1
if (-not $filesLine) {
    throw "No single-line 'files: [...]' entry found in $Package."
}
$files = $filesLine.Matches[0].Groups[1].Value -split ',' |
    ForEach-Object { $_.Trim().Trim('"', "'") } |
    Where-Object { $_ }

foreach ($file in $files) {
    if (-not (Test-Path -LiteralPath (Join-Path $BaseRoot $file) -PathType Leaf)) {
        throw "Base file '$file' listed in $Package does not exist in $BaseRoot."
    }
}

$localFile = [System.IO.Path]::ChangeExtension($PackageFile, ".local.yaml")
$localRelative = [System.IO.Path]::GetRelativePath($ProjectRoot, $localFile) -replace '\\', '/'

# Never write a file with local paths that Git would pick up.
& git -C $ProjectRoot check-ignore --quiet -- $localRelative
if ($LASTEXITCODE -ne 0) {
    throw "$localRelative is not ignored by Git in $ProjectRoot. Add '*.local.yaml' to the project's .gitignore first."
}

$lines = @(
    "# Generated by waveshare-esphome-base/scripts/use-local-base.ps1."
    "# Loads the base from a local working tree. Never commit this file."
    ""
    "packages:"
)
for ($i = 0; $i -lt $files.Count; $i++) {
    $lines += "  waveshare_base_local_${i}: !include $BaseRoot/$($files[$i])"
}
$lines += @(
    ""
    "external_components:"
    "  - source:"
    "      type: local"
    "      path: $BaseRoot/components"
    "    components: [waveshare_ui]"
)

Set-Content -LiteralPath $localFile -Value $lines -Encoding utf8NoBOM
Write-Host "Wrote $localRelative"
Write-Host "Use: esphome -s waveshare_base_package $localRelative config <root yaml>"
